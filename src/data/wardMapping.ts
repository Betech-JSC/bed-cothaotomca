function stripAccentsLower(str: string): string {
  if (!str) return "";
  return str
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

function resolveCanonicalDistrictFromText(rawDistrict?: string, contextText?: string): string {
  const sources = [rawDistrict || "", contextText || ""];
  for (const src of sources) {
    const norm = stripAccentsLower(src);
    if (!norm) continue;

    if (
      norm.includes("thu duc") ||
      /\b(quan|q\.?)\s*0?[29]\b/.test(norm) ||
      norm === "2" ||
      norm === "9"
    ) {
      return "TP. Thủ Đức";
    }

    const numMatch = norm.match(/(?:^|[\s,.\-/(])(?:quan|q\.?)?\s*0?(10|11|12|[1-8])(?=$|[\s,.\-/)])/);
    if (
      numMatch &&
      (norm.includes("quan") || /\bq\.?\s*0?(10|11|12|[1-8])\b/.test(norm) || /^\d+$/.test(norm))
    ) {
      return `Quận ${parseInt(numMatch[1], 10)}`;
    }

    if (norm.includes("go vap")) return "Gò Vấp";
    if (norm.includes("binh thanh")) return "Bình Thạnh";
    if (norm.includes("phu nhuan")) return "Phú Nhuận";
    if (norm.includes("tan binh")) return "Tân Bình";
    if (norm.includes("tan phu")) return "Tân Phú";
    if (norm.includes("binh tan")) return "Bình Tân";
    if (norm.includes("binh chanh")) return "Huyện Bình Chánh";
    if (norm.includes("hoc mon")) return "Huyện Hóc Môn";
    if (norm.includes("nha be")) return "Huyện Nhà Bè";
  }
  return "";
}

/**
 * Helper loại bỏ tiền tố đơn vị hành chính không phân biệt hoa thường:
 * Phường, Xã, Thị trấn, Quận, Huyện, Thành phố, TP., TP, TT., TT, P., P, Q., Q, H., H, TX., TX.
 */
export function cleanAdministrativeUnitName(name: string): string {
  if (!name) return "";
  return name
    .trim()
    .replace(
      /^(?:(?:phường|xã|thị\s+trấn|quận|huyện|thành\s+phố)\s+|(?:tp|tt|tx|p|q|h)(?:\.\s*|\s+))/iu,
      ""
    )
    .trim();
}

/**
 * Format label:
 * [Tên Phường Mới]
 */
export function formatWardLabel(wardName: string, _district?: string, _oldWard?: string): string {
  if (!wardName) return "";
  const cleanWardName = wardName.trim();

  const hasPrefix =
    cleanWardName.startsWith("Phường") ||
    cleanWardName.startsWith("Xã") ||
    cleanWardName.startsWith("Thị trấn");
  const prefix = hasPrefix ? "" : "Phường ";

  return `${prefix}${cleanWardName}`;
}

/**
 * Loại bỏ các phần tử trùng lặp trong chuỗi địa chỉ giao hàng:
 * - Khử trùng lặp tên phường/xã và quận/huyện liền kề (VD: "Tân Sơn Nhất, Tân Sơn Nhất" -> "Tân Sơn Nhất")
 * - Khử trùng lặp khi một phần tử đã chứa trọn vẹn phần tử liền kề (VD: "64 Út Tịch, Tân Sơn Nhất", "Tân Sơn Nhất" -> "64 Út Tịch, Tân Sơn Nhất")
 */
export function cleanDuplicateAddressParts(fullAddress: string): string {
  if (!fullAddress) return "";
  const rawParts = fullAddress
    .split(",")
    .map((p) => p.trim())
    .filter(Boolean);

  if (rawParts.length <= 1) return fullAddress.trim();

  const result: string[] = [];

  for (let i = 0; i < rawParts.length; i++) {
    const current = rawParts[i];
    if (result.length === 0) {
      result.push(current);
      continue;
    }

    const prev = result[result.length - 1];
    const normPrev = cleanAdministrativeUnitName(prev).toLowerCase();
    const normCurrent = cleanAdministrativeUnitName(current).toLowerCase();

    // 1. Trùng lặp chính xác hoặc trùng sau khi bỏ tiền tố hành chính (VD: "Tân Sơn Nhất" vs "Tân Sơn Nhất")
    if (normCurrent && (normPrev === normCurrent || normCurrent === prev.toLowerCase())) {
      continue;
    }

    // 2. Nếu phần trước đã kết thúc bằng chính phần hiện tại
    if (normCurrent && (normPrev.endsWith(normCurrent) || prev.toLowerCase().endsWith(normCurrent))) {
      continue;
    }

    // 3. Nếu phần trước phân tách bởi dấu nối [-–] và phân đoạn cuối trùng với phần hiện tại
    const prevSubParts = prev
      .split(/[-–]/)
      .map((s) => cleanAdministrativeUnitName(s).toLowerCase())
      .filter(Boolean);
    const lastSubPart = prevSubParts[prevSubParts.length - 1] || "";
    if (normCurrent && (lastSubPart === normCurrent || lastSubPart.endsWith(normCurrent))) {
      continue;
    }

    result.push(current);
  }

  return result.join(", ");
}

/**
 * Ghép các thành phần địa chỉ (Số nhà tên đường, Phường/Xã, Quận/Huyện, Tỉnh/Thành)
 * và tự động khử trùng lặp nếu tên Phường và Quận trùng nhau hoặc bị lặp.
 */
export function buildDeliveryAddress(
  streetAddress?: string | null,
  ward?: string | null,
  district?: string | null,
  province?: string | null
): string {
  const parts = [streetAddress, ward, district, province]
    .map((p) => (p || "").trim())
    .filter(Boolean);

  return cleanDuplicateAddressParts(parts.join(", "));
}

/**
 * Tự động tìm tên Phường mới sáp nhập (theo Nghị quyết 1685/NQ-UBTVQH15) từ tên Phường cũ và Quận/Huyện.
 * Bắt buộc đối chiếu kèm Quận/Huyện trước khi khớp số phường để không quy nhầm P.1, P.2, P.12 về Phường Gia Định.
 */
export function resolveNewWardName(
  oldWardName: string,
  district?: string,
  contextText?: string
): string | null {
  if (!oldWardName) return null;
  const cleanWard = oldWardName.trim();
  const strippedWard = cleanAdministrativeUnitName(cleanWard);
  const normStrippedWard = stripAccentsLower(strippedWard);
  const normCtx = stripAccentsLower(contextText || "");
  const canonDist = resolveCanonicalDistrictFromText(district, contextText);

  // 1. Nếu tên truyền vào đã là tên Phường mới trong 94 phường/xã (trừ trường hợp P. Tân Phú cũ ở Quận 9 / Thủ Đức)
  if (!(canonDist === "TP. Thủ Đức" && normStrippedWard === "tan phu")) {
    for (const newWard of Object.keys(HCMC_WARD_OLD_NAME_MAP)) {
      if (stripAccentsLower(newWard) === normStrippedWard) {
        const validDists = WARD_PRIMARY_DISTRICT_MAP[newWard] || [];
        if (!canonDist || validDists.includes(canonDist)) {
          return newWard;
        }
      }
    }
  }

  // 2. Trích xuất số phường nếu là dạng P.14, Phường 14, 14
  const numMatch = cleanWard.match(/^(?:p\.?|phường|phuong)?\s*0?(\d{1,2})\b/i);
  const wardNum = numMatch ? parseInt(numMatch[1], 10) : null;

  if (wardNum !== null) {
    // 2a. Các quận có quy tắc phân tách chi tiết theo Nghị quyết 1685/NQ-UBTVQH15
    if (canonDist === "Gò Vấp") {
      if (wardNum === 1 || wardNum === 3 || wardNum === 4 || wardNum === 7) return "Hạnh Thông";
      if (wardNum === 5 || wardNum === 6) return "An Nhơn";
      if (wardNum === 10 || wardNum === 17) return "Gò Vấp";
      if (wardNum === 8 || wardNum === 9 || wardNum === 11) return "Thông Tây Hội";
      if (wardNum === 12 || wardNum === 14) return "An Hội Tây";
      if (wardNum === 13 || wardNum === 15 || wardNum === 16) return "An Hội Đông";
    }

    if (canonDist === "Tân Bình") {
      if (wardNum >= 1 && wardNum <= 3) return "Tân Sơn Hòa";
      if (wardNum === 4 || wardNum === 5 || wardNum === 7) return "Tân Sơn Nhất";
      if (wardNum === 6 || wardNum === 8 || wardNum === 9) return "Tân Hòa";
      if (wardNum >= 10 && wardNum <= 12) return "Bảy Hiền";
      if (wardNum === 13 || wardNum === 14) return "Tân Bình";
      if (wardNum === 15) {
        if (/(phan huy ich|tan son|pham van bach|cong lo|nguyen phuc chu)/.test(normCtx)) {
          return "Tân Sơn";
        }
        return "Tân Bình";
      }
    }

    if (canonDist === "Phú Nhuận") {
      if (wardNum === 1 || wardNum === 2 || wardNum === 7) return "Cầu Kiệu";
      if (wardNum === 3 || wardNum === 4 || wardNum === 5 || wardNum === 9) return "Đức Nhuận";
      if (wardNum === 15 && /(phan xich long|van kiep|hoa phuong|hoa lan|hoa cuc)/.test(normCtx)) {
        return "Cầu Kiệu";
      }
      if ([8, 10, 11, 12, 13, 14, 15, 17].includes(wardNum)) return "Phú Nhuận";
    }

    if (canonDist === "Bình Thạnh") {
      if ([1, 2, 3, 7, 15, 17].includes(wardNum)) return "Gia Định";
      if ([5, 6, 11, 13].includes(wardNum)) return "Bình Lợi Trung";
      if ([12, 14, 24, 26].includes(wardNum)) return "Bình Thạnh";
      if ([19, 21, 22, 25].includes(wardNum)) return "Thạnh Mỹ Tây";
      if (wardNum === 27 || wardNum === 28) return "Bình Quới";
    }

    if (canonDist === "Quận 3") {
      if (normCtx.includes("rach bung binh")) return "Nhiêu Lộc";
      if (wardNum >= 9 && wardNum <= 14) return "Nhiêu Lộc";
      if (wardNum >= 6 && wardNum <= 8) return "Xuân Hòa";
      if (
        wardNum === 4 &&
        /(vo thi sau|nam ky khoi nghia|hai ba trung|pasteur|pham ngoc thach|tran quoc toan|ly chinh thang)/.test(
          normCtx
        )
      ) {
        return "Xuân Hòa";
      }
      if (wardNum >= 1 && wardNum <= 5) return "Bàn Cờ";
    }

    if (canonDist === "Quận 10") {
      if (wardNum === 12 || wardNum === 13 || wardNum === 15) return "Hòa Hưng";
      if (wardNum === 6 || wardNum === 8) return "Diên Hồng";
      if (wardNum === 14) {
        if (/(3 thang 2|ba thang hai|nguyen tri phuong|thanh thai|ly thuong kiet)/.test(normCtx)) {
          return "Diên Hồng";
        }
        return "Hòa Hưng";
      }
      if ([1, 2, 3, 4, 5, 7, 9, 10, 11].includes(wardNum)) return "Vườn Lài";
    }

    // 2b. Tra cứu theo HCMC_WARD_OLD_NAME_MAP có kiểm tra chặt canonDist
    if (canonDist) {
      const normalizedWard = `p.${wardNum}`;
      for (const [newWard, oldWards] of Object.entries(HCMC_WARD_OLD_NAME_MAP)) {
        const validDists = WARD_PRIMARY_DISTRICT_MAP[newWard] || [];
        if (!validDists.includes(canonDist)) continue;
        const list = oldWards.split(",").map((s) => s.trim().toLowerCase());
        if (list.some((item) => item === normalizedWard)) {
          return newWard;
        }
      }
      return null;
    }

    // 2c. Khi KHÔNG có thông tin Quận: chỉ các phường số 19..28 là duy nhất tại Quận Bình Thạnh
    if (wardNum >= 19 && wardNum <= 28) {
      const normalizedWard = `p.${wardNum}`;
      for (const [newWard, oldWards] of Object.entries(HCMC_WARD_OLD_NAME_MAP)) {
        const validDists = WARD_PRIMARY_DISTRICT_MAP[newWard] || [];
        if (!validDists.includes("Bình Thạnh")) continue;
        const list = oldWards.split(",").map((s) => s.trim().toLowerCase());
        if (list.some((item) => item === normalizedWard)) {
          return newWard;
        }
      }
    }

    return null;
  }

  // 3. Tra cứu Phường/Xã có tên chữ (VD: "P. Thảo Điền", "P. Bến Nghé", "P. Võ Thị Sáu", "Xã Bình Hưng")
  for (const [newWard, oldWards] of Object.entries(HCMC_WARD_OLD_NAME_MAP)) {
    if (canonDist) {
      const validDists = WARD_PRIMARY_DISTRICT_MAP[newWard] || [];
      if (!validDists.includes(canonDist)) continue;
    }
    const items = oldWards.split(",").map((s) => stripAccentsLower(cleanAdministrativeUnitName(s)));
    if (items.some((item) => item && item === normStrippedWard)) {
      return newWard;
    }
  }

  return null;
}

